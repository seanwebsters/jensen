import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const dir = dirname(fileURLToPath(import.meta.url));
const r = await build({ entryPoints: [join(dir, 'js/run.js')], bundle: true, minify: true, format: 'iife', write: false, target: 'es2020', legalComments: 'none', loader: { '.jpg': 'dataurl' } });
const js = r.outputFiles[0].text.replace(/<\/script/g, '<\\/script');
const uri = (f, t = 'image/jpeg') => `data:${t};base64,` + readFileSync(join(dir, 'assets', f)).toString('base64');
const icon = uri('icon.png', 'image/png');
const html = readFileSync(join(dir, 'index.src.html'), 'utf8').replace('__KEYP__', uri('keyp.jpg')).replace('__KEY__', uri('key.jpg')).replace('__OVER__', uri('over.jpg')).replace('__ICON__', icon).replace('/*__GAME__*/', () => js);
writeFileSync(join(dir, 'index.html'), html);
console.log('index.html', (html.length / 1024).toFixed(0) + ' KB');
